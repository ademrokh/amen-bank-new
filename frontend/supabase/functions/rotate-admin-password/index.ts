import { createClient } from 'jsr:@supabase/supabase-js@2.110.0';
import nodemailer from 'npm:nodemailer@6.10.0';

// These must be set in the Supabase Dashboard → Edge Functions → Secrets:
// SERVICE_ROLE_KEY, GMAIL_ADDRESS, GMAIL_APP_PASSWORD
const SUPABASE_URL = Deno.env.get('SUPABASE_URL') || 'https://afjtwgekoqzfwmgoiwoy.supabase.co';
const SERVICE_ROLE_KEY = Deno.env.get('SERVICE_ROLE_KEY') ?? '';
const GMAIL_ADDRESS = Deno.env.get('GMAIL_ADDRESS') ?? '';
const GMAIL_APP_PASSWORD = Deno.env.get('GMAIL_APP_PASSWORD') ?? '';

Deno.serve(async (req) => {
  if (req.method !== 'POST') {
    return new Response(JSON.stringify({ error: 'Method not allowed' }), {
      status: 405,
      headers: { 'Content-Type': 'application/json' },
    });
  }

  let body: { user_id?: string; pre_generated_password?: string };
  try {
    body = await req.json();
  } catch {
    return new Response(JSON.stringify({ error: 'Invalid JSON body' }), {
      status: 400,
      headers: { 'Content-Type': 'application/json' },
    });
  }

  const { user_id, pre_generated_password } = body;

  if (!user_id) {
    return new Response(JSON.stringify({ error: 'Missing user_id' }), {
      status: 400,
      headers: { 'Content-Type': 'application/json' },
    });
  }

  if (!SERVICE_ROLE_KEY) {
    return new Response(JSON.stringify({ error: 'SERVICE_ROLE_KEY is not set in edge function secrets' }), {
      status: 500,
      headers: { 'Content-Type': 'application/json' },
    });
  }

  if (!GMAIL_ADDRESS || !GMAIL_APP_PASSWORD) {
    return new Response(JSON.stringify({ error: 'GMAIL_ADDRESS or GMAIL_APP_PASSWORD is not set in edge function secrets' }), {
      status: 500,
      headers: { 'Content-Type': 'application/json' },
    });
  }

  // The password to email — always pre-generated by the Next.js route
  const newPassword = pre_generated_password;
  if (!newPassword) {
    return new Response(JSON.stringify({ error: 'Missing pre_generated_password' }), {
      status: 400,
      headers: { 'Content-Type': 'application/json' },
    });
  }

  // Look up the user's email from Supabase Auth
  const supabase = createClient(SUPABASE_URL, SERVICE_ROLE_KEY);
  const { data: userData, error: userError } = await supabase.auth.admin.getUserById(user_id);

  if (userError || !userData?.user?.email) {
    console.error('User lookup failed:', userError);
    return new Response(JSON.stringify({ error: 'User not found in Supabase Auth' }), {
      status: 404,
      headers: { 'Content-Type': 'application/json' },
    });
  }

  const recipientEmail = userData.user.email;

  // Send email via Gmail SMTP
  try {
    const transporter = nodemailer.createTransport({
      service: 'gmail',
      auth: {
        user: GMAIL_ADDRESS,
        pass: GMAIL_APP_PASSWORD,
      },
    });

    await transporter.sendMail({
      from: `"Amen Bank Admin" <${GMAIL_ADDRESS}>`,
      to: recipientEmail,
      subject: '🔐 Your new admin password',
      html: `
        <div style="background:#0f172a;padding:40px 20px;font-family:'Segoe UI',Tahoma,Geneva,Verdana,sans-serif;">
          <div style="max-width:480px;margin:0 auto;background:#ffffff;border-radius:12px;overflow:hidden;box-shadow:0 25px 50px -12px rgba(0,0,0,0.25);">

            <div style="background:#006B3C;padding:28px 36px;">
              <h1 style="color:#ffffff;margin:0;font-size:20px;font-weight:700;">Amen Bank</h1>
              <p style="color:rgba(255,255,255,0.75);margin:6px 0 0;font-size:13px;">Admin Portal — Security Update</p>
            </div>

            <div style="padding:36px;">
              <p style="color:#334155;font-size:15px;line-height:1.6;margin:0 0 24px;">
                A new one-time password has been generated for your admin account.
                Use it to sign in — <strong>it will expire immediately after use.</strong>
              </p>

              <div style="background:#f8fafc;border:2px dashed #cbd5e1;border-radius:8px;padding:24px;text-align:center;margin-bottom:28px;">
                <p style="color:#94a3b8;font-size:11px;text-transform:uppercase;letter-spacing:1.5px;margin:0 0 10px;font-weight:700;">
                  One-Time Password
                </p>
                <p style="color:#0f172a;font-size:30px;font-weight:800;letter-spacing:4px;margin:0;font-family:'Courier New',monospace;">
                  ${newPassword}
                </p>
              </div>

              <p style="color:#64748b;font-size:13px;margin:0;">
                If you did not request this password, please secure your account immediately.
              </p>
            </div>

            <div style="background:#f8fafc;padding:18px 36px;border-top:1px solid #e2e8f0;">
              <p style="color:#94a3b8;font-size:11px;text-align:center;margin:0;line-height:1.5;">
                Amen Bank · 50, Avenue Mohamed V · Tunis 1002<br>
                © ${new Date().getFullYear()} Amen Bank. All rights reserved.
              </p>
            </div>

          </div>
        </div>
      `,
    });

    console.log(`Password email sent to ${recipientEmail}`);
    return new Response(JSON.stringify({ success: true, message: 'Email sent successfully' }), {
      status: 200,
      headers: { 'Content-Type': 'application/json' },
    });
  } catch (err) {
    const message = err instanceof Error ? err.message : 'Unknown SMTP error';
    console.error('Failed to send email:', message);
    return new Response(JSON.stringify({ error: `Failed to send email: ${message}` }), {
      status: 500,
      headers: { 'Content-Type': 'application/json' },
    });
  }
});